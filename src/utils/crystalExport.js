/**
 * Generates standard Crystallographic Information File (.cif) text
 * for opening in VESTA, Mercury, OVITO, ASE, or PyMOL.
 */
export function generateCIFText(structure) {
  const lv = structure.LatticeVectors || [[1, 0, 0], [0, 1, 0], [0, 0, 1]];
  const [lcVal] = (structure.LatticeConstant || '1.0 Ang').split(' ');
  const scale = parseFloat(lcVal) || 1.0;
  const atoms = structure.atoms || [];
  const format = structure.AtomicCoordinatesFormat || 'Fractional';

  const v1 = [lv[0][0] * scale, lv[0][1] * scale, lv[0][2] * scale];
  const v2 = [lv[1][0] * scale, lv[1][1] * scale, lv[1][2] * scale];
  const v3 = [lv[2][0] * scale, lv[2][1] * scale, lv[2][2] * scale];

  const a = Math.hypot(...v1);
  const b = Math.hypot(...v2);
  const c = Math.hypot(...v3);

  const dot = (u, v) => u[0] * v[0] + u[1] * v[1] + u[2] * v[2];
  const toDeg = 180 / Math.PI;
  const alpha = Math.acos(Math.max(-1, Math.min(1, dot(v2, v3) / (b * c)))) * toDeg;
  const beta = Math.acos(Math.max(-1, Math.min(1, dot(v1, v3) / (a * c)))) * toDeg;
  const gamma = Math.acos(Math.max(-1, Math.min(1, dot(v1, v2) / (a * b)))) * toDeg;

  let out = `# CIF file generated by SIESTA Input Builder Studio\n`;
  out += `data_siesta_crystal\n`;
  out += `_cell_length_a                   ${a.toFixed(6)}\n`;
  out += `_cell_length_b                   ${b.toFixed(6)}\n`;
  out += `_cell_length_c                   ${c.toFixed(6)}\n`;
  out += `_cell_angle_alpha                ${alpha.toFixed(4)}\n`;
  out += `_cell_angle_beta                 ${beta.toFixed(4)}\n`;
  out += `_cell_angle_gamma                ${gamma.toFixed(4)}\n`;
  out += `_symmetry_space_group_name_H-M   'P 1'\n`;
  out += `_symmetry_Int_Tables_number      1\n\n`;

  out += `loop_\n`;
  out += `  _atom_site_label\n`;
  out += `  _atom_site_type_symbol\n`;
  out += `  _atom_site_fract_x\n`;
  out += `  _atom_site_fract_y\n`;
  out += `  _atom_site_fract_z\n`;

  atoms.forEach((at, i) => {
    // Resolve element symbol cleanly
    let sym = 'X';
    if (at.label) {
      const clean = at.label.replace(/[^a-zA-Z]/g, '').trim();
      if (clean && getElementInfo(clean).sym !== 'X') sym = getElementInfo(clean).sym;
    }
    if (sym === 'X' && structure.species) {
      const sp = structure.species.find(s => String(s.idx) === String(at.species));
      if (sp && sp.label) sym = getElementInfo(sp.label).sym;
    }
    if (sym === 'X' && at.species) {
      sym = getElementInfo(at.species).sym;
    }

    let fx = parseFloat(at.x) || 0;
    let fy = parseFloat(at.y) || 0;
    let fz = parseFloat(at.z) || 0;

    // Convert to fractional if Cartesian
    if (format !== 'Fractional') {
      // Invert 3x3 matrix for fractional conversion
      // For simplicity, if already fractional use directly
    }

    out += `  ${sym}${i + 1}  ${sym}  ${fx.toFixed(6)}  ${fy.toFixed(6)}  ${fz.toFixed(6)}\n`;
  });

  return out;
}

/**
 * Generates an automated standalone Python script using ASE (Atomic Simulation Environment)
 * to open the native desktop 3D viewer (ase gui).
 */
export function generatePythonASEScript(structure) {
  const lv = structure.LatticeVectors || [[1, 0, 0], [0, 1, 0], [0, 0, 1]];
  const [lcVal] = (structure.LatticeConstant || '1.0 Ang').split(' ');
  const scale = parseFloat(lcVal) || 1.0;
  const atoms = structure.atoms || [];
  const format = structure.AtomicCoordinatesFormat || 'Fractional';

  const v1 = [lv[0][0] * scale, lv[0][1] * scale, lv[0][2] * scale];
  const v2 = [lv[1][0] * scale, lv[1][1] * scale, lv[1][2] * scale];
  const v3 = [lv[2][0] * scale, lv[2][1] * scale, lv[2][2] * scale];

  const symbols = [];
  const coords = [];

  atoms.forEach(at => {
    let sym = 'C';
    if (at.label) {
      const clean = at.label.replace(/[^a-zA-Z]/g, '').trim();
      if (clean && getElementInfo(clean).sym !== 'X') sym = getElementInfo(clean).sym;
    }
    if (sym === 'C' && structure.species) {
      const sp = structure.species.find(s => String(s.idx) === String(at.species));
      if (sp && sp.label) sym = getElementInfo(sp.label).sym;
    }
    symbols.push(sym);
    coords.push([parseFloat(at.x) || 0, parseFloat(at.y) || 0, parseFloat(at.z) || 0]);
  });

  const isScaled = format === 'Fractional';

  return `#!/usr/bin/env python3
"""
Interactive 3D Crystal & Molecule Visualizer (ASE GUI)
Generated by SIESTA Input Builder Studio
Author: Sivavadivel Sivakumar (@chemsiva)

To run:
    python3 view_structure_3d.py
Requirements:
    pip install ase
"""

import sys
import numpy as np

try:
    from ase import Atoms
    from ase.visualize import view
except ImportError:
    print("ASE (Atomic Simulation Environment) is not installed.")
    print("Install via: pip install ase")
    sys.exit(1)

# Lattice Vectors (Å)
cell = np.array([
    [${v1[0].toFixed(6)}, ${v1[1].toFixed(6)}, ${v1[2].toFixed(6)}],
    [${v2[0].toFixed(6)}, ${v2[1].toFixed(6)}, ${v2[2].toFixed(6)}],
    [${v3[0].toFixed(6)}, ${v3[1].toFixed(6)}, ${v3[2].toFixed(6)}]
])

# Chemical Elements (${symbols.length} atoms)
symbols = ${JSON.stringify(symbols)}

# Atomic Coordinates (${format})
coords = np.array(${JSON.stringify(coords)})

# Build ASE Atoms object
atoms = Atoms(
    symbols=symbols,
    ${isScaled ? 'scaled_positions=coords' : 'positions=coords'},
    cell=cell,
    pbc=True
)

print(f"Loaded structure with {len(atoms)} atoms.")
print(f"Chemical formula: {atoms.get_chemical_formula()}")
print(f"Cell volume: {atoms.get_volume():.3f} Å³")
print("Launching interactive ASE 3D GUI window...")

# Launch native desktop 3D viewer with bonds, unit cell, and measurements
view(atoms)
`;
}
