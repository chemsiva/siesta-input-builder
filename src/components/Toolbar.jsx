import { useRef } from 'react';
import { useFDFStore } from '../store/fdfStore';
import templates from '../data/templates.json';
import { generateConvergenceSuite } from '../utils/convergenceGenerator';
import JSZip from 'jszip';

export function Toolbar() {
  const getFDFText    = useFDFStore(s => s.getFDFText);
  const loadFromText  = useFDFStore(s => s.loadFromText);
  const loadFromCIF   = useFDFStore(s => s.loadFromCIF);
  const validate      = useFDFStore(s => s.validate);
  const loadTemplate  = useFDFStore(s => s.loadTemplate);
  const setActiveSection = useFDFStore(s => s.setActiveSection);
  const activeSection    = useFDFStore(s => s.activeSection);
  const reset         = useFDFStore(s => s.reset);
  const system        = useFDFStore(s => s.system);
  const errors        = useFDFStore(s => s.validationErrors);
  const theme         = useFDFStore(s => s.theme || 'dark');
  const toggleTheme   = useFDFStore(s => s.toggleTheme);
  const fullState     = useFDFStore(s => s);
  const pseudoSettings = useFDFStore(s => s.pseudoSettings || {});
  const cifRef  = useRef();

  const rawLabel = system.SystemLabel || 'siesta';
  const label = rawLabel.replace(/[/\\?%*:|"<>]/g, '_').replace(/\.\./g, '_').trim() || 'siesta';
  const pseudoPath = (pseudoSettings.pseudoPath || '').trim().replace(/\/+$/, '');
  const MAX_FILE_SIZE = 50 * 1024 * 1024; // 50 MB DoS / memory-exhaustion limit

  // ── Plain .fdf download ──────────────────────────────────────────────────
  const download = () => {
    const text = getFDFText();
    const blob = new Blob([text], { type: 'text/plain' });
    const a = document.createElement('a');
    a.href = URL.createObjectURL(blob);
    a.download = `${label}.fdf`;
    a.click();
    URL.revokeObjectURL(a.href);
  };

  // ── Package download: .fdf + run_siesta.sh ───────────────────────────────
  const downloadPackage = async () => {
    const fdfText = getFDFText();
    const nprocs  = 4; // sensible default; user edits the script

    const runScript = `#!/bin/bash
# =============================================================
#  SIESTA run script — generated by SIESTA Input Builder
#  Edit NPROCS to match your machine (run: nproc to check).
# =============================================================
set -euo pipefail

NPROCS=\${1:-${nprocs}}
FDF="${label}.fdf"
OUT="${label}.out"
${pseudoPath ? `
# ── Pseudopotential search path ───────────────────────────────
# SIESTA looks for Element.psf / Element.psml here automatically.
export SIESTA_PS_PATH="${pseudoPath}"
export SIESTA_PP_PATH="${pseudoPath}"
echo "  Pseudo path: ${pseudoPath}"` : `
# No pseudopotential path set.
# Copy your .psf/.psml files into this folder, or set SIESTA_PS_PATH manually:
#   export SIESTA_PS_PATH=/path/to/your/pseudos`}

echo "============================================================"
echo " Running SIESTA on \${NPROCS} cores"
echo " Input : \${FDF}"
echo " Output: \${OUT}"
echo "============================================================"

mpirun -np "\${NPROCS}" siesta < "\${FDF}" | tee "\${OUT}"

echo "Done. Check \${OUT} for results."
`;

    const zip = new JSZip();
    zip.file(`${label}.fdf`, fdfText);
    zip.file('run_siesta.sh', runScript);
    zip.file('README.txt',
`SIESTA Calculation Package
===========================
Files:
  ${label}.fdf    — SIESTA input file
  run_siesta.sh   — Run script (sets SIESTA_PS_PATH, calls mpirun)

Usage:
  bash run_siesta.sh 16     # run on 16 cores
  bash run_siesta.sh        # default: 4 cores
${pseudoPath ? `
Pseudopotential path: ${pseudoPath}
SIESTA will search this directory for .psf/.psml files automatically.
Your pseudo files do NOT need to be in this folder.` : `
No pseudo path was set in the GUI.
Either copy your .psf/.psml files here, or edit run_siesta.sh to set
  export SIESTA_PS_PATH=/path/to/your/pseudos`}
`);

    const blob = await zip.generateAsync({ type: 'blob' });
    const a = document.createElement('a');
    a.href = URL.createObjectURL(blob);
    a.download = `${label}_siesta_package.zip`;
    a.click();
    URL.revokeObjectURL(a.href);
  };

  const handleLoad = (e) => {
    const file = e.target.files[0];
    if (!file) return;
    if (file.size > MAX_FILE_SIZE) {
      alert('⚠️ Security Warning: File exceeds 50 MB limit. Please upload a standard SIESTA .fdf file.');
      e.target.value = '';
      return;
    }
    const reader = new FileReader();
    reader.onload = ev => loadFromText(ev.target.result);
    reader.readAsText(file);
    e.target.value = '';
  };

  const handleLoadCIF = (e) => {
    const file = e.target.files[0];
    if (!file) return;
    if (file.size > MAX_FILE_SIZE) {
      alert('⚠️ Security Warning: File exceeds 50 MB limit. Please upload a standard CIF file.');
      e.target.value = '';
      return;
    }
    const reader = new FileReader();
    reader.onload = ev => loadFromCIF(ev.target.result);
    reader.readAsText(file);
    e.target.value = '';
  };

  const handleValidate = () => {
    const errs = validate();
    if (errs.length === 0) alert('✅ No issues found — input looks valid!');
  };

  const handleDownloadConvergence = async (type) => {
    try {
      const zipBlob = await generateConvergenceSuite(fullState, type);
      const a = document.createElement('a');
      a.href = URL.createObjectURL(zipBlob);
      a.download = `siesta_${type}_convergence.zip`;
      a.click();
    } catch (e) {
      console.error(e);
      alert('Failed to generate convergence suite: ' + e.message);
    }
  };

  return (
    <div className="toolbar">
      <div className="toolbar-left">
        <span className="toolbar-brand">⚗️ SIESTA Input Builder <span className="toolbar-ver">5.4.2</span></span>
      </div>

      <div className="toolbar-center">
        {/* Templates */}
        <div className="dropdown">
          <button className="btn btn-secondary">📋 Templates ▾</button>
          <div className="dropdown-menu">
            {Object.entries(templates).map(([key, t]) => (
              <button key={key} className="dropdown-item" onClick={() => loadTemplate(key)}>
                <strong>{t.label}</strong>
                <span className="dropdown-desc">{t.description}</span>
              </button>
            ))}
          </div>
        </div>

        {/* Convergence Suite */}
        <div className="dropdown">
          <button className="btn btn-secondary">⚡ Convergence Suite ▾</button>
          <div className="dropdown-menu">
            <button className="dropdown-item" onClick={() => handleDownloadConvergence('mesh')}>
              <strong>MeshCutoff Sweep (.zip)</strong>
              <span className="dropdown-desc">150 to 500 Ry series + run_mesh.sh + plot.py</span>
            </button>
            <button className="dropdown-item" onClick={() => handleDownloadConvergence('kgrid')}>
              <strong>K-Grid Sweep (.zip)</strong>
              <span className="dropdown-desc">4×4×4 to 12×12×12 series + run_kgrid.sh</span>
            </button>
          </div>
        </div>
      </div>
      <div className="toolbar-right">
        <button
          className={`btn ${activeSection === 'output' ? 'btn-primary' : 'btn-secondary'}`}
          onClick={() => setActiveSection('output')}
          title="View and analyze SIESTA output files (.out, .MDE, .ANI)">
          📊 Output Viewer
        </button>

        <button className="btn btn-secondary" onClick={() => fileRef.current.click()}>
          📂 Load .fdf
        </button>
        <input ref={fileRef} type="file" accept=".fdf,.txt" style={{display:'none'}} onChange={handleLoad} />

        <button className="btn btn-secondary" onClick={() => cifRef.current.click()} title="Import crystal structure from CIF file">
          💎 Import CIF
        </button>
        <input ref={cifRef} type="file" accept=".cif" style={{display:'none'}} onChange={handleLoadCIF} />

        <button
          className={`btn ${errors.length > 0 ? 'btn-warning' : 'btn-secondary'}`}
          onClick={handleValidate}>
          🔍 Validate{errors.length > 0 ? ` (${errors.length})` : ''}
        </button>

        {/* Plain .fdf */}
        <button className="btn btn-primary" onClick={download} title="Download .fdf file only">
          ⬇ Download .fdf
        </button>

        {/* Package ZIP: .fdf + run_siesta.sh with SIESTA_PS_PATH */}
        <button
          className="btn btn-primary"
          style={{ background: pseudoPath ? 'var(--success)' : undefined, opacity: pseudoPath ? 1 : 0.75 }}
          onClick={downloadPackage}
          title={pseudoPath
            ? `Download .fdf + run_siesta.sh with SIESTA_PS_PATH=${pseudoPath}`
            : 'Download .fdf + run_siesta.sh (set pseudo path in Species section first)'}>
          📦 Download Package
          {pseudoPath && <span style={{ fontSize: '0.7rem', marginLeft: '4px', opacity: 0.85 }}>+path</span>}
        </button>
        <button
          className="btn btn-secondary"
          onClick={toggleTheme}
          title={`Switch to ${theme === 'dark' ? 'Light' : 'Dark'} mode`}
          style={{ padding: '0.3rem 0.6rem', fontSize: '0.85rem' }}>
          {theme === 'dark' ? '☀️ Light' : '🌙 Dark'}
        </button>

        <button className="btn btn-ghost" onClick={() => { if(confirm('Reset all fields to defaults?')) reset(); }}
          title="Reset to defaults">↺</button>
      </div>
    </div>
  );
}
