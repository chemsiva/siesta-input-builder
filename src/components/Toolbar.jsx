import { useRef, useState } from 'react';
import { useFDFStore } from '../store/fdfStore';
import templates from '../data/templates.json';
import { generateConvergenceSuite } from '../utils/convergenceGenerator';
import JSZip from 'jszip';

export function Toolbar() {
 const getFDFText = useFDFStore(s => s.getFDFText);
 const loadFromText = useFDFStore(s => s.loadFromText);
  const loadFromCIF = useFDFStore(s => s.loadFromCIF);
  const loadOutFromText = useFDFStore(s => s.loadOutFromText);
  const validate = useFDFStore(s => s.validate);
 const loadTemplate = useFDFStore(s => s.loadTemplate);
 const setActiveSection = useFDFStore(s => s.setActiveSection);
 const activeSection = useFDFStore(s => s.activeSection);
 const reset = useFDFStore(s => s.reset);
 const system = useFDFStore(s => s.system);
 const errors = useFDFStore(s => s.validationErrors);
 const theme = useFDFStore(s => s.theme || 'dark');
 const toggleTheme = useFDFStore(s => s.toggleTheme);
 const fullState = useFDFStore(s => s);
 const pseudoSettings = useFDFStore(s => s.pseudoSettings || {});
  const fileRef = useRef();
  const cifRef = useRef();
  const outRef = useRef();
  const rawLabel = system?.SystemLabel || 'siesta';
  const label = rawLabel.replace(/[/\\?%*:|"<>]/g, '_').replace(/\.\./g, '_').trim() || 'siesta';
  const pseudoPath = (pseudoSettings.pseudoPath || '').trim().replace(/\/+$/, '');
  const MAX_FILE_SIZE = 50 * 1024 * 1024; // 50 MB DoS / memory-exhaustion limit
  const [showCiteModal, setShowCiteModal] = useState(false);
  const [copyFeedback, setCopyFeedback] = useState('');

 // ── Plain .fdf download ──────────────────────────────────────────────────
 const download = () => {
 const text = getFDFText();
 const blob = new Blob([text], { type: 'text/plain' });
 const a = document.createElement('a');
 a.href = URL.createObjectURL(blob);
 a.download = `${label}.fdf`;
 a.click();
 URL.revokeObjectURL(a.href);
 };

 // ── Package download: .fdf + run_siesta.sh ───────────────────────────────
 const downloadPackage = async () => {
 const fdfText = getFDFText();
 const nprocs = 4; // sensible default; user edits the script

 const runScript = `#!/bin/bash
# =============================================================
# SIESTA run script — generated by SIESTA Input Builder
# Edit NPROCS to match your machine (run: nproc to check).
# =============================================================
set -euo pipefail

NPROCS=\${1:-${nprocs}}
FDF="${label}.fdf"
OUT="${label}.out"
${pseudoPath ? `
# ── Pseudopotential search path ───────────────────────────────
# SIESTA looks for Element.psf / Element.psml here automatically.
export SIESTA_PS_PATH="${pseudoPath}"
export SIESTA_PP_PATH="${pseudoPath}"
echo " Pseudo path: ${pseudoPath}"` : `
# No pseudopotential path set.
# Copy your .psf/.psml files into this folder, or set SIESTA_PS_PATH manually:
# export SIESTA_PS_PATH=/path/to/your/pseudos`}

echo "============================================================"
echo " Running SIESTA on \${NPROCS} cores"
echo " Input : \${FDF}"
echo " Output: \${OUT}"
echo "============================================================"

mpirun -np "\${NPROCS}" siesta < "\${FDF}" | tee "\${OUT}"

echo "Done. Check \${OUT} for results."
`;

 const zip = new JSZip();
 zip.file(`${label}.fdf`, fdfText);
 zip.file('run_siesta.sh', runScript);
 zip.file('README.txt',
`SIESTA Calculation Package
===========================
Files:
 ${label}.fdf — SIESTA input file
 run_siesta.sh — Run script (sets SIESTA_PS_PATH, calls mpirun)

Usage:
 bash run_siesta.sh 16 # run on 16 cores
 bash run_siesta.sh # default: 4 cores
${pseudoPath ? `
Pseudopotential path: ${pseudoPath}
SIESTA will search this directory for .psf/.psml files automatically.
Your pseudo files do NOT need to be in this folder.` : `
No pseudo path was set in the GUI.
Either copy your .psf/.psml files here, or edit run_siesta.sh to set
 export SIESTA_PS_PATH=/path/to/your/pseudos`}
`);

 const blob = await zip.generateAsync({ type: 'blob' });
 const a = document.createElement('a');
 a.href = URL.createObjectURL(blob);
 a.download = `${label}_siesta_package.zip`;
 a.click();
 URL.revokeObjectURL(a.href);
 };

 const handleLoad = (e) => {
 const file = e.target.files[0];
 if (!file) return;
 if (file.size > MAX_FILE_SIZE) {
 alert('Security Warning: File exceeds 50 MB limit. Please upload a standard SIESTA .fdf file.');
 e.target.value = '';
 return;
 }
 const reader = new FileReader();
 reader.onload = ev => loadFromText(ev.target.result);
 reader.readAsText(file);
 e.target.value = '';
 };

 const handleLoadCIF = (e) => {
 const file = e.target.files[0];
 if (!file) return;
 if (file.size > MAX_FILE_SIZE) {
 alert('Security Warning: File exceeds 50 MB limit. Please upload a standard CIF file.');
 e.target.value = '';
 return;
 }
 const reader = new FileReader();
 reader.onload = ev => loadFromCIF(ev.target.result);
    reader.readAsText(file);
    e.target.value = '';
  };

  const handleLoadOut = (e) => {
    const file = e.target.files?.[0];
    if (!file) return;
    const reader = new FileReader();
    reader.onload = (ev) => {
      try {
        loadOutFromText(ev.target.result);
      } catch (err) {
        alert('Failed to parse SIESTA output: ' + err.message);
      }
    };
    reader.readAsText(file);
    e.target.value = '';
  };
 const handleValidate = () => {
 const errs = validate();
 if (errs.length === 0) alert('No issues found — input looks valid!');
 };

 const handleDownloadConvergence = async (type) => {
 try {
 const zipBlob = await generateConvergenceSuite(fullState, type);
 const a = document.createElement('a');
 a.href = URL.createObjectURL(zipBlob);
 a.download = `siesta_${type}_convergence.zip`;
 a.click();
 } catch (e) {
 console.error(e);
 alert('Failed to generate convergence suite: ' + e.message);
 }
 };

 return (
 <div className="toolbar">
 <div className="toolbar-left">
 <span className="toolbar-brand">SIESTA Input Builder <span className="toolbar-ver">5.4.2</span></span>
 </div>

 <div className="toolbar-center">
 {/* Templates */}
 <div className="dropdown">
 <button className="btn btn-secondary">Templates ▾</button>
 <div className="dropdown-menu">
 {Object.entries(templates).map(([key, t]) => (
 <button key={key} className="dropdown-item" onClick={() => loadTemplate(key)}>
 <strong>{t.label}</strong>
 <span className="dropdown-desc">{t.description}</span>
 </button>
 ))}
 </div>
 </div>

 {/* Convergence Suite */}
 <div className="dropdown">
 <button className="btn btn-secondary">Convergence Suite ▾</button>
 <div className="dropdown-menu">
 <button className="dropdown-item" onClick={() => handleDownloadConvergence('mesh')}>
 <strong>MeshCutoff Sweep (.zip)</strong>
 <span className="dropdown-desc">150 to 500 Ry series + run_mesh.sh + plot.py</span>
 </button>
 <button className="dropdown-item" onClick={() => handleDownloadConvergence('kgrid')}>
 <strong>K-Grid Sweep (.zip)</strong>
 <span className="dropdown-desc">4×4×4 to 12×12×12 series + run_kgrid.sh</span>
 </button>
 </div>
 </div>
 </div>
 <div className="toolbar-right">
 <button
 className={`btn ${activeSection === 'output' ? 'btn-primary' : 'btn-secondary'}`}
 onClick={() => setActiveSection('output')}
 title="View and analyze SIESTA output files (.out, .MDE, .ANI)">
 Output Viewer
 </button>

      <a
        href="./SIESTA_Universal_Guide.pdf"
        target="_blank"
        rel="noopener noreferrer"
        className="btn btn-secondary"
        title="Open comprehensive 20-page SIESTA Universal Guide & DFT Handbook (PDF)"
        style={{ textDecoration: 'none' }}>
        User Guide
      </a>

      <button
        type="button"
        className="btn btn-secondary"
        onClick={() => setShowCiteModal(true)}
        title="Cite & Acknowledge this tool in your research"
        style={{ color: 'var(--accent)', fontWeight: 600 }}>
        Cite
      </button>
 <button className="btn btn-secondary" onClick={() => fileRef.current.click()}>
 Load .fdf
 </button>
 <input ref={fileRef} type="file" accept=".fdf,.txt" style={{display:'none'}} onChange={handleLoad} />

      <button className="btn btn-secondary" onClick={() => cifRef.current.click()} title="Import crystal structure from CIF file">
        Import CIF
      </button>
      <input ref={cifRef} type="file" accept=".cif" style={{display:'none'}} onChange={handleLoadCIF} />

      <button className="btn btn-secondary" onClick={() => outRef.current.click()} title="Import final SIESTA calculation output (.out) to extract all features and display simplified note">
        Import Result (.out)
      </button>
      <input ref={outRef} type="file" accept=".out,.log,.txt" style={{display:'none'}} onChange={handleLoadOut} />
 <button
 className={`btn ${errors.length > 0 ? 'btn-warning' : 'btn-secondary'}`}
 onClick={handleValidate}>
 Validate{errors.length > 0 ? ` (${errors.length})` : ''}
 </button>

 {/* Plain .fdf */}
 <button className="btn btn-primary" onClick={download} title="Download .fdf file only">
 Download .fdf
 </button>

 {/* Package ZIP: .fdf + run_siesta.sh with SIESTA_PS_PATH */}
 <button
 className="btn btn-primary"
 style={{ background: pseudoPath ? 'var(--success)' : undefined, opacity: pseudoPath ? 1 : 0.75 }}
 onClick={downloadPackage}
 title={pseudoPath
 ? `Download .fdf + run_siesta.sh with SIESTA_PS_PATH=${pseudoPath}`
 : 'Download .fdf + run_siesta.sh (set pseudo path in Species section first)'}>
 Download Package
 {pseudoPath && <span style={{ fontSize: '0.7rem', marginLeft: '4px', opacity: 0.85 }}>+path</span>}
 </button>
 <button
 className="btn btn-secondary"
 onClick={toggleTheme}
 title={`Switch to ${theme === 'dark' ? 'Light' : 'Dark'} mode`}
 style={{ padding: '0.3rem 0.6rem', fontSize: '0.85rem' }}>
 {theme === 'dark' ? 'Light' : 'Dark'}
 </button>

 <button className="btn btn-ghost" onClick={() => { if(confirm('Reset all fields to defaults?')) reset(); }}
 title="Reset to defaults">Reset</button>
      </div>

      {/* Citation & Acknowledgement Modal */}
      {showCiteModal && (
        <div style={{
          position: 'fixed',
          top: 0, left: 0, right: 0, bottom: 0,
          backgroundColor: 'rgba(0, 0, 0, 0.75)',
          backdropFilter: 'blur(4px)',
          zIndex: 1000,
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'center',
          padding: '1rem',
        }} onClick={() => setShowCiteModal(false)}>
          <div style={{
            background: 'var(--surface)',
            border: '1px solid var(--border)',
            borderRadius: '10px',
            maxWidth: '620px',
            width: '100%',
            padding: '1.4rem',
            boxShadow: '0 8px 32px rgba(0,0,0,0.6)',
            position: 'relative',
          }} onClick={e => e.stopPropagation()}>
            <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '0.8rem' }}>
              <strong style={{ fontSize: '1.05rem', color: 'var(--fg)' }}>
                Cite &amp; Acknowledge this Software
              </strong>
              <button
                type="button"
                className="btn btn-ghost btn-sm"
                onClick={() => setShowCiteModal(false)}
                style={{ fontSize: '1rem', lineHeight: 1 }}>
                ✕
              </button>
            </div>

            <p style={{ fontSize: '0.82rem', color: 'var(--muted)', lineHeight: 1.5, marginBottom: '1rem' }}>
              If this tool assisted in your computational research, crystal structure preparation, or post-DFT analysis, please acknowledge or cite:
            </p>

            {/* Author Credit Chip */}
            <div style={{ background: 'var(--surface2)', padding: '0.6rem 0.8rem', borderRadius: '6px', border: '1px solid var(--border)', marginBottom: '1rem' }}>
              <div style={{ fontSize: '0.74rem', color: 'var(--muted)' }}>Lead Developer / Author:</div>
              <div style={{ fontSize: '0.92rem', fontWeight: 700, color: 'var(--accent)' }}>
                Sivavadivel Sivakumar <span style={{ fontSize: '0.78rem', color: 'var(--muted)', fontWeight: 400 }}>(@chemsiva)</span>
              </div>
              <div style={{ fontSize: '0.74rem', color: 'var(--muted)', marginTop: '2px' }}>
                Repository: <a href="https://github.com/chemsiva/siesta-input-builder" target="_blank" rel="noopener noreferrer" style={{ color: '#38bdf8' }}>github.com/chemsiva/siesta-input-builder</a>
              </div>
            </div>

            {/* 1. Paper Acknowledgement */}
            <div style={{ marginBottom: '1rem' }}>
              <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '4px' }}>
                <span style={{ fontSize: '0.78rem', fontWeight: 600 }}>Paper Acknowledgement:</span>
                <button
                  type="button"
                  className="btn btn-xs btn-secondary"
                  onClick={async () => {
                    const text = `The DFT input files and post-processing analysis were prepared using the SIESTA Input Builder & Post-DFT Analysis Studio developed by Sivavadivel Sivakumar (https://github.com/chemsiva/siesta-input-builder).`;
                    await navigator.clipboard.writeText(text);
                    setCopyFeedback('ack');
                    setTimeout(() => setCopyFeedback(''), 2500);
                  }}>
                  {copyFeedback === 'ack' ? 'Copied!' : 'Copy Text'}
                </button>
              </div>
              <textarea
                readOnly
                rows={3}
                value={`The DFT input files and post-processing analysis were prepared using the SIESTA Input Builder & Post-DFT Analysis Studio developed by Sivavadivel Sivakumar (https://github.com/chemsiva/siesta-input-builder).`}
                style={{ width: '100%', fontSize: '0.75rem', padding: '0.5rem', background: '#090d16', border: '1px solid var(--border)', borderRadius: '4px', color: 'var(--fg)', resize: 'none' }}
              />
            </div>

            {/* 2. BibTeX Citation */}
            <div style={{ marginBottom: '1rem' }}>
              <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '4px' }}>
                <span style={{ fontSize: '0.78rem', fontWeight: 600 }}>BibTeX Reference:</span>
                <button
                  type="button"
                  className="btn btn-xs btn-primary"
                  onClick={async () => {
                    const bib = `@software{sivakumar2026siesta,\n  author = {Sivakumar, Sivavadivel},\n  title = {SIESTA Input Builder \\& Post-DFT Analysis Studio},\n  year = {2026},\n  publisher = {GitHub},\n  journal = {GitHub repository},\n  url = {https://github.com/chemsiva/siesta-input-builder}\n}`;
                    await navigator.clipboard.writeText(bib);
                    setCopyFeedback('bib');
                    setTimeout(() => setCopyFeedback(''), 2500);
                  }}>
                  {copyFeedback === 'bib' ? 'Copied BibTeX!' : 'Copy BibTeX'}
                </button>
              </div>
              <pre style={{ margin: 0, padding: '0.6rem', fontSize: '0.72rem', background: '#090d16', border: '1px solid var(--border)', borderRadius: '4px', color: '#38bdf8', overflowX: 'auto' }}>
{`@software{sivakumar2026siesta,
  author = {Sivakumar, Sivavadivel},
  title = {SIESTA Input Builder \\& Post-DFT Analysis Studio},
  year = {2026},
  publisher = {GitHub},
  journal = {GitHub repository},
  url = {https://github.com/chemsiva/siesta-input-builder}
}`}
              </pre>
            </div>

            {/* 3. Single-Handed Work & Mandatory Manual Verification Disclaimer */}
            <div style={{
              background: 'rgba(245, 158, 11, 0.08)',
              border: '1px solid rgba(245, 158, 11, 0.3)',
              borderRadius: '6px',
              padding: '0.65rem 0.8rem',
              marginBottom: '1rem',
              fontSize: '0.74rem',
              lineHeight: 1.5,
              color: 'var(--fg)',
            }}>
              <strong style={{ color: '#f59e0b', display: 'block', marginBottom: '2px' }}>
                ⚠️ Single-Handed Project &amp; Scientific Verification Disclaimer:
              </strong>
              This software is an independent, single-handed project designed and developed solely by <strong>Sivavadivel Sivakumar</strong>.
              The author assumes <strong>no responsibility or liability</strong> for any software bugs, numerical inaccuracies, data mismatches, or failed supercomputer runs.
              Users must manually inspect, check, and verify all generated parameters, coordinate tables, and units before running calculations on HPC clusters or publishing research.
            </div>

            <div style={{ textAlign: 'right' }}>
              <button
                type="button"
                className="btn btn-sm btn-secondary"
                onClick={() => setShowCiteModal(false)}>
                Close
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
